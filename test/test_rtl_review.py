def test_rtl_review_tracks_delta_confidence_and_exact_waivers(tmp_path: Path, monkeypatch):
    rtl = tmp_path / "cpu.v"
    rtl.write_text(
        "module cpu(input clk, input en, output y); wire gated_clk; "
        "assign gated_clk = clk & en; assign y = gated_clk; endmodule\n",
        encoding="utf-8",
    )
    spec = CreateWorkspaceData(
        directory=str(tmp_path / "ws_review_delta"),
        parameters={"Design": "cpu", "Top module": "cpu"},
        origin_verilog=str(rtl),
    )
    create_workspace(spec)
    workspace = load_workspace(str(tmp_path / "ws_review_delta"))
    engine = EngineFlow(workspace=workspace)
    engine.create_step_workspaces()
    _mock_successful_yosys_precheck(monkeypatch)

    assert engine.run_step("review", rerun=True) == StateEnum.Success
    report_path = Path(workspace["directory"]) / "review_fe" / "report" / "rtl_review.json"
    first = json.loads(report_path.read_text(encoding="utf-8"))
    issue = next(item for item in first["issues"] if item["title"] == "Clock generated by RTL logic")
    assert issue["status"] == "new"
    assert issue["confidence"] == "medium"
    assert issue["origin"] == "source_heuristic"
    assert issue["ownership"] == "cpu"
    assert len(issue["fingerprint"]) == 64

    workspace["review_waivers"] = [{
        "fingerprint": issue["fingerprint"],
        "reason": "Reviewed clock-gating experiment",
    }]
    assert engine.run_step("review", rerun=True) == StateEnum.Success
    second = json.loads(report_path.read_text(encoding="utf-8"))
    waived = next(item for item in second["issues"] if item["fingerprint"] == issue["fingerprint"])
    assert waived["status"] == "existing"
    assert waived["waived"] is True
    assert waived["waiver"]["reason"] == "Reviewed clock-gating experiment"
    assert second["delta"]["existing"] >= 1

    Path(workspace["origin_verilog"]).write_text(
        "module cpu(input clk, output y); assign y = clk; endmodule\n",
        encoding="utf-8",
    )
    assert engine.run_step("review", rerun=True) == StateEnum.Success
    third = json.loads(report_path.read_text(encoding="utf-8"))
    assert issue["fingerprint"] in {item["fingerprint"] for item in third["resolved_issues"]}
    assert third["delta"]["resolved"] >= 1


