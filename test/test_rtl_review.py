def _stat_path_from_script(script_text: str) -> Path:
    marker = "tee -o "
    line = next(line for line in script_text.splitlines() if line.startswith(marker))
    raw = line.removeprefix(marker).split(" stat -json", maxsplit=1)[0].strip()
    return Path(raw.strip('"')).resolve()


def _netlist_path_from_script(script_text: str) -> Path:
    marker = "write_json "
    line = next(line for line in script_text.splitlines() if line.startswith(marker))
    raw = line.removeprefix(marker).strip()
    return Path(raw.strip('"')).resolve()


