def test_errors_of_the_limited_frontend_do_not_block_review() -> None:
    diagnostics = [
        {"severity": "error", "category": "syntax", "message": "syntax error, unexpected TOK_ID"},
        {"severity": "warning", "category": "lint", "message": "w"},
    ]

    limited = _as_frontend_limits(diagnostics)

    assert [item["category"] for item in limited] == ["tool-limit", "lint"]
    assert not any(_diagnostic_blocks_review(item) for item in limited)
    assert _quality_from_run(1, limited, {})["gate"] == "warnings"
    assert _quality_from_run(1, diagnostics, {})["gate"] == "failed"


def test_frontend_failure_without_a_parsed_error_is_still_a_tool_limit() -> None:
    limited = _as_frontend_limits([])

    assert len(limited) == 1
    assert limited[0]["category"] == "tool-limit"
    assert "slang plugin" in limited[0]["message"]


def test_paths_with_spaces_are_detected() -> None:
    inputs = {"rtl_files": ["/a/top.sv", "/my designs/core.sv"], "incdirs": ["/inc dir"]}

    assert _paths_with_whitespace(inputs) == ["/my designs/core.sv", "/inc dir"]
    assert _paths_with_whitespace({"rtl_files": ["/a/top.sv"], "incdirs": ["/inc"]}) == []
