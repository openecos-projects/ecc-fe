def _titles(text: str, tmp_path: Path) -> list[tuple[int, str, str]]:
    path = tmp_path / "dut.sv"
    path.write_text(text, encoding="utf-8")
    issues: list[dict] = []
    _scan_source(SourceFile(path=path, text=text), issues)
    return [(issue["line"], issue["severity"], issue["title"]) for issue in issues]


def _has(titles, title: str) -> list[int]:
    return [line for line, _, found in titles if found == title]


# --- heuristics -------------------------------------------------------------


def test_commented_out_code_is_not_reviewed(tmp_path) -> None:
    text = (
        "module m;\n"
        "  // assign clk_div = clk_i & a;\n"
        "  /* assign clk_bad = a & b;\n"
        "     case (s) 2'd0: x = 1; endcase */\n"
        "  assign y = a; // case (s)\n"
        "endmodule\n"
    )

    assert _titles(text, tmp_path) == []


@pytest.mark.parametrize(
    "statement",
    [
        "assign clk_o = clk_i;",
        "assign clk = wb_clk_i;",
        "assign clk_en = a & b;",
        "assign clk_sel = a ? b : c;",
        "assign clk_cnt_next = clk_cnt + 1;",
        "assign sys_clock_valid = lock & ready;",
    ],
)
def test_clock_names_that_are_not_generated_clocks(tmp_path, statement) -> None:
    assert _titles(f"module m;\n  {statement}\nendmodule\n", tmp_path) == []


@pytest.mark.parametrize(
    "statement",
    ["assign clk_gated = clk_i & en;", "assign clk_div = ~clk_div_r;", "assign core_clk = sel ? clk_a : clk_b;"],
)
def test_generated_clock_is_a_warning_not_an_error(tmp_path, statement) -> None:
    titles = _titles(f"module m;\n  {statement}\nendmodule\n", tmp_path)

    assert titles == [(2, "warning", "Clock generated by RTL logic")]


def test_clock_in_condition_needs_a_clock_name_not_a_substring(tmp_path) -> None:
    text = (
        "module m;\n"
        "  always @(posedge clk) if (!MUL_CLKGATE || active) q <= d;\n"
        "  always @(posedge clk) if (clk_en) q <= d;\n"
        "  always @(*) if (clk) y = 1; else y = 0;\n"
        "endmodule\n"
    )

    assert _has(_titles(text, tmp_path), "Clock used in data condition") == [4]


def test_async_reset_is_one_note_per_file(tmp_path) -> None:
    block = "  always @(posedge clk or negedge rst_n) if (!rst_n) q <= 0; else q <= d;\n"
    titles = _titles("module m;\n" + block * 5 + "endmodule\n", tmp_path)

    assert titles == [(2, "info", "Asynchronous reset in sequential blocks")]


@pytest.mark.parametrize(
    ("opening", "flagged"),
    [
        ("always @*", True),
        ("always @(*)", True),
        ("always @( * )", True),
        ("always_comb", True),
        ("always_ff @(posedge clk)", False),
    ],
)
def test_incomplete_if_is_seen_in_every_combinational_form(tmp_path, opening, flagged) -> None:
    text = f"module m;\n  {opening} begin\n    if (a) y = 1;\n  end\nendmodule\n"

    found = _has(_titles(text, tmp_path), "Combinational if without visible else")

    assert found == ([2] if flagged else [])


def test_defaults_before_the_if_mean_no_latch(tmp_path) -> None:
    text = (
        "module m;\n"
        "  always_comb begin\n"
        "    y = '0;\n"
        "    if (a) y = 1;\n"
        "  end\n"
        "  always_comb begin\n"
        "    if (b) z = 1;\n"
        "  end\n"
        "endmodule\n"
    )

    assert _has(_titles(text, tmp_path), "Combinational if without visible else") == [6]


def test_if_rule_does_not_read_into_the_next_block(tmp_path) -> None:
    text = (
        "module m;\n"
        "  always_comb begin\n"
        "    if (a) y = 1;\n"
        "  end\n"
        "  always_ff @(posedge clk)\n"
        "    if (b) q <= 1; else q <= 0;\n"
        "endmodule\n"
    )

    assert _has(_titles(text, tmp_path), "Combinational if without visible else") == [2]


def test_case_default_rules(tmp_path) -> None:
    filler = "".join(f"      8'd{n}: y = {n};\n" for n in range(1, 90))
    text = (
        "module m;\n"
        "  always_comb begin\n"
        "    y = 0;\n"
        "    unique case (s)\n      2'd0: y = 1;\n    endcase\n"          # 4: unique
        "    priority casez (s)\n      2'b1?: y = 1;\n    endcase\n"     # 7: priority
        "    case (s)\n      2'd0: y = 1;\n    endcase\n"                # 10: flagged
        "    case (t)\n" + filler + "      default: y = 0;\n    endcase\n"  # 13: far default
        "  end\n"
        "endmodule\n"
    )

    assert _has(_titles(text, tmp_path), "Case statement lacks a visible default branch") == [10]


def test_case_rule_stops_at_its_own_endcase(tmp_path) -> None:
    text = (
        "module m;\n"
        "  always_comb begin\n"
        "    y = 0;\n"
        "    case (s)\n      2'd0: y = 1;\n    endcase\n"
        "    case (t)\n      2'd0: y = 2;\n      default: y = 3;\n    endcase\n"
        "  end\n"
        "endmodule\n"
    )

    assert _has(_titles(text, tmp_path), "Case statement lacks a visible default branch") == [4]


def test_comment_slashes_are_not_operators(tmp_path) -> None:
    text = "module m;\n  assign y = a; // ---------- // ---------- // ----------\nendmodule\n"

    assert _titles(text, tmp_path) == []


# --- fingerprints and waivers -------------------------------------------------

_DUT = (
    "module m;\n"
    "  assign clk_gated = clk_i & en;\n"
    "  assign clk_gated = clk_i & en;\n"
    "  assign clk_other = clk_i | en;\n"
    "endmodule\n"
)


def _review(tmp_path: Path, text: str, waivers=None, previous=None, root: str = "rtl") -> dict:
    directory = tmp_path / root
    directory.mkdir(exist_ok=True)
    source = directory / "dut.sv"
    source.write_text(text, encoding="utf-8")
    filelist = directory / "design.f"
    filelist.write_text("dut.sv\n", encoding="utf-8")
    workspace = {"frontend_design_kind": "generic_rtl", "input_filelist": str(filelist)}
    issues: list[dict] = []
    _scan_source(SourceFile(path=source, text=text), issues)
    return finalize_review_report(
        {"issues": issues, "summary": {}}, previous, waivers or [], workspace
    )


def test_fingerprints_survive_edits_above_and_a_different_checkout(tmp_path) -> None:
    first = _review(tmp_path, _DUT)
    shifted = _review(tmp_path, "// header\n// more\n" + _DUT)
    elsewhere = _review(tmp_path, _DUT, root="other-checkout")

    prints = [issue["fingerprint"] for issue in first["issues"]]
    assert len(set(prints)) == 3  # two identical lines are told apart
    assert [issue["fingerprint"] for issue in shifted["issues"]] == prints
    assert [issue["fingerprint"] for issue in elsewhere["issues"]] == prints
    assert [issue["line"] for issue in shifted["issues"]] == [4, 5, 6]


def test_changing_the_line_itself_changes_the_fingerprint(tmp_path) -> None:
    first = _review(tmp_path, _DUT)
    edited = _review(tmp_path, _DUT.replace("clk_i | en", "clk_i ^ en"))

    assert first["issues"][2]["fingerprint"] != edited["issues"][2]["fingerprint"]
    assert first["issues"][0]["fingerprint"] == edited["issues"][0]["fingerprint"]


def test_waiver_keeps_applying_after_code_moves(tmp_path) -> None:
    target = _review(tmp_path, _DUT)["issues"][2]
    waivers = [{"fingerprint": target["fingerprint"], "reason": "reviewed"}]

    moved = _review(tmp_path, "// one\n// two\n// three\n" + _DUT, waivers=waivers)

    assert [issue["waived"] for issue in moved["issues"]] == [False, False, True]
    assert moved["waivers"] == {"configured": 1, "applied": 1, "invalid": []}
    assert moved["summary"]["actionable_warnings"] == 2


def test_waiver_written_with_the_old_fingerprint_still_applies(tmp_path) -> None:
    report = _review(tmp_path, _DUT)
    legacy = report["issues"][0]["legacy_fingerprint"]
    assert legacy != report["issues"][0]["fingerprint"]

    waived = _review(tmp_path, _DUT, waivers=[{"fingerprint": legacy, "reason": "old"}])

    assert waived["issues"][0]["waived"] is True


def test_delta_against_the_previous_run_ignores_line_moves(tmp_path) -> None:
    previous = _review(tmp_path, _DUT)

    current = _review(tmp_path, "// moved\n" + _DUT, previous=previous)

    assert current["delta"] == {"baseline": "previous_run", "new": 0, "existing": 3, "resolved": 0}


def test_legacy_fingerprint_is_unchanged(tmp_path) -> None:
    issue = {
        "origin": "source_heuristic", "severity": "warning", "category": "clock",
        "title": "T", "source": "/abs/dut.sv", "line": 7,
    }
    identity = {
        "origin": "source_heuristic", "severity": "warning", "category": "clock",
        "title": "T", "source": "/abs/dut.sv", "line": 7,
    }
    import hashlib

    expected = hashlib.sha256(
        json.dumps(identity, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode()
    ).hexdigest()

    assert _legacy_issue_fingerprint(issue, {}) == expected
    assert _issue_fingerprint(issue, {}) != expected


def test_issue_without_a_source_gets_an_empty_anchor() -> None:
    issues = [{"title": "Design level", "source": "", "line": 0}]

    _assign_anchors(issues)

    assert (issues[0]["anchor"], issues[0]["occurrence"]) == ("", 0)


