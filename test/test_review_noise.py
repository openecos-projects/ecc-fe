def test_review_takes_the_users_sources_from_the_prepare_result(tmp_path) -> None:
    cpu = tmp_path / "cpu" / "core.sv"
    soc = tmp_path / "soc" / "top.v"
    for path in (cpu, soc):
        path.parent.mkdir()
        path.write_text("module x; endmodule\n", encoding="utf-8")
    workspace: dict = {"cpu_filelist": "", "soc_filelist": ""}
    manifest = tmp_path / "prepared_inputs.json"
    manifest.write_text(
        json.dumps(
            {
                "rtl_files": [str(cpu), str(soc)],
                "rtl_sources": [
                    {"path": str(cpu), "ownership": "cpu"},
                    {"path": str(soc), "ownership": "soc"},
                ],
                "incdirs": [str(tmp_path / "inc")],
                "header_files": [str(tmp_path / "hdr" / "defs.svh")],
                "libdirs": [str(tmp_path / "lib")],
                "defines": ["A=1"],
                "source_fingerprint": workspace_input_fingerprint(workspace),
            }
        ),
        encoding="utf-8",
    )
    workspace["prepared_manifest"] = str(manifest)

    inputs = prepared_review_inputs(workspace)

    assert inputs is not None
    assert inputs["rtl_files"] == [str(cpu)]
    assert inputs["incdirs"] == [
        str(tmp_path / "inc"), str(tmp_path / "hdr"), str(tmp_path / "cpu"), str(tmp_path / "lib"),
    ]
    assert inputs["defines"] == ["A=1"]


def test_review_falls_back_without_a_prepare_result(tmp_path) -> None:
    assert prepared_review_inputs({}) is None
    assert prepared_review_inputs({"prepared_manifest": str(tmp_path / "absent.json")}) is None


