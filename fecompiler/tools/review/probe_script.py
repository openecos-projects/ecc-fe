"""Write the Yosys script of the structural precheck.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from fecompiler.tools.review.probe_inputs import (
    _cpu_top,
    _review_defines,
)


def _build_yosys_script(
    inputs: dict[str, Any],
    workspace: dict[str, Any],
    stat_path: Path,
    netlist_path: Path,
    *,
    frontend: str = "read_verilog",
) -> str:
    top = _cpu_top(workspace, inputs)
    read_lines = (
        _build_read_slang_script(inputs, top)
        if frontend == "read_slang"
        else [_build_read_verilog_command(inputs)]
    )

    hierarchy = " ".join([
        "hierarchy",
        f"-top {_quote_yosys(top, quote=False)}" if top else "-auto-top",
        # read_verilog has no library search; hierarchy reads <module>.v from
        # these directories for the modules still missing. read_slang searches
        # them itself, as elaboration does.
        *(
            f"-libdir {_quote_yosys(str(directory), quote=False)}"
            for directory in (inputs.get("libdirs", []) if frontend != "read_slang" else [])
        ),
        "-check",
    ])
    return "\n".join([
        "# Auto-generated by ECOS frontend RTL Review.",
        "# Structural precheck only. This script stops before implementation and netlist handoff.",
        *read_lines,
        hierarchy,
        "proc",
        "opt_expr",
        "opt_clean",
        "check",
        f"tee -o {_quote_yosys(str(stat_path))} stat -json",
        f"write_json {_quote_yosys(str(netlist_path))}",
        "",
    ])


def _paths_with_whitespace(inputs: dict[str, Any]) -> list[str]:
    return [
        str(path)
        for path in (
            *inputs.get("rtl_files", []),
            *inputs.get("incdirs", []),
            *inputs.get("libdirs", []),
        )
        if any(char.isspace() for char in str(path))
    ]


def _as_frontend_limits(diagnostics: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Mark the errors of a limited frontend as tool limits, which do not block."""
    limited = [
        {**item, "category": "tool-limit"} if str(item.get("severity", "")).lower() == "error" else item
        for item in diagnostics
    ]
    if not any(str(item.get("severity", "")).lower() == "error" for item in limited):
        limited.append({
            "severity": "error",
            "category": "tool-limit",
            "message": "Yosys read_verilog could not read the SystemVerilog sources; the slang plugin is not installed.",
            "source": "",
            "line": 0,
            "column": 0,
        })
    return limited


def _build_read_verilog_command(inputs: dict[str, Any]) -> str:
    read_args: list[str] = ["read_verilog", "-sv", "-defer"]
    for incdir in inputs.get("incdirs", []):
        read_args.append(f"-I{_quote_yosys(str(incdir), quote=False)}")
    for define in _review_defines(inputs):
        read_args.append(f"-D{_quote_yosys(str(define), quote=False)}")
    read_args.extend(_quote_yosys(str(path)) for path in inputs.get("rtl_files", []))
    return " ".join(read_args)


def _build_read_slang_script(inputs: dict[str, Any], top: str) -> list[str]:
    read_args: list[str] = [
        "read_slang",
        "--compat-mode",
        "--allow-use-before-declare",
        "--ignore-timing",
        "--ignore-assertions",
        "-Wduplicate-definition",
    ]
    for module_name in inputs.get("blackboxed_modules", []):
        read_args.extend(["--blackboxed-module", _quote_yosys(str(module_name), quote=False)])
    if top:
        read_args.extend(["--top", _quote_yosys(top, quote=False)])
    for incdir in inputs.get("incdirs", []):
        read_args.append(f"-I{_quote_yosys(str(incdir), quote=False)}")
    for define in _review_defines(inputs):
        read_args.append(f"+define+{_quote_yosys(str(define), quote=False)}")
    # The library options of elaboration (rtl_inputs.slang_library_args).
    for directory in inputs.get("libdirs", []):
        read_args.extend(["-y", _quote_yosys(str(directory), quote=False)])
    for extension in inputs.get("libexts", []):
        read_args.extend(["-Y", _quote_yosys(str(extension), quote=False)])
    read_args.extend(_quote_yosys(str(path), quote=False) for path in inputs.get("rtl_files", []))
    return [
        "plugin -i slang",
        " ".join(read_args),
    ]


def _quote_yosys(value: str, *, quote: bool = True) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"' if quote else escaped
